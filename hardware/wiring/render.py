"""Build the scheduled harness drawings and the two converter installation sheets."""

import csv
from collections import Counter, defaultdict
from pathlib import Path
from tempfile import TemporaryDirectory

import yaml
from wireviz import wireviz


ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT / "generated"
SUPPLY_SHEETS = ("pi-power.yaml", "hk4-hub-power.yaml")


def write_csv(path, fields, rows):
    with path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.writer(stream, lineterminator="\n")
        writer.writerow(fields)
        writer.writerows(rows)


def render_svg(source, output):
    drawing = wireviz.parse(source, return_types="svg")
    (output / source.with_suffix(".svg").name).write_text(drawing, encoding="utf-8", newline="\n")


def new_sheet(name):
    if name == "power":
        revision = "0.6"
        title = "PS1  /  ESP32 hub power branches"
        subtitle = (
            "P01–P03 share 2 A. Each positive lead has its own proposed fuse in PS1."
            "\\nCarrier positions are component-side, antenna up. Verify VIN and USB isolation on the fitted board."
        )
    else:
        revision = "0.3"
        title = f"{name}  /  Sensor harnesses"
        subtitle = "Bench pin assignments · proposed lengths in feet"
    return {
        "metadata": {"title": title, "revision": revision},
        "options": {"fontname": "Arial", "mini_bom_mode": False},
        "tweak": {"override": {"graph": {
            "label": f"{title}\\nRev {revision} · PROPOSED\\n{subtitle}",
            "labelloc": "t", "labeljust": "l", "fontsize": "16",
            "ranksep": "0.48", "nodesep": "0.35", "pad": "0.24",
            "pack": "true", "packmode": "array_ci1",
        }}},
        "connectors": {}, "cables": {}, "connections": [],
    }


def build_sheet(name, cables, families, output):
    sheet = new_sheet(name)
    endpoints = []
    source_note = "# Generated by ../render.py from cable_schedule.csv and families.yaml.\n"
    # With rankdir=LR, dot packs disconnected rows from bottom to top.
    for row in cables if name == "power" else reversed(cables):
        wire = row["cable"]
        family = families[row["family"]]
        left, right = row["from_endpoint"], row["to_endpoint"]
        count = len(family["destination"]["pins"])
        source = dict(family["source"], bgcolor_title="#dce8f2")
        destination = dict(family["destination"], bgcolor_title="#ddeddf", notes=row["destination_location"])
        source_pins = source["pins"][:count]

        if name == "power":
            # Group three fused outputs on one PS1 block. Pin IDs describe function.
            hub = right.split()[0]
            source_pins = [f"{hub} {pin}" for pin in source_pins]
            supply = sheet["connectors"].setdefault(left, dict(source, pins=[], pinlabels=[]))
            supply["pins"].extend(source_pins)
            supply["pinlabels"].extend(source["pinlabels"])
        else:
            sheet["connectors"][left] = source
        sheet["connectors"][right] = destination
        sheet["cables"][wire] = dict(family["cable"], length=f'{row["length_ft"]} ft', bgcolor_title="#f6e8cf")
        sheet["connections"].append([
            {left: source_pins}, {wire: list(range(1, count + 1))}, {right: destination["pins"]},
        ])
        if "shield_source" in family:
            sheet["connections"].append([{left: family["shield_source"]}, {wire: "s"}])

        for end, interface, pins in [(left, source, source_pins), (right, destination, destination["pins"])]:
            # Shield landings are separate from the numbered contact set.
            if end == left and "shield_source" in family:
                pins = [*pins, family["shield_source"]]
            for pin, label in zip(pins, interface["pinlabels"], strict=True):
                endpoints.append([end, pin, label, interface["type"], wire, row["status"]])

    if name == "power":
        power = families["CBL-P"]
        feed = power["supply"]
        fanouts = {row["from_endpoint"] for row in cables}
        if len(fanouts) != 1:
            raise ValueError("The HK4 power drawing requires one shared fused fanout")
        fanout = fanouts.pop()
        # Continue at the terminals where the feed pair lands on the upstream sheet.
        upstream = yaml.safe_load((ROOT / "hk4-hub-power.yaml").read_text(encoding="utf-8"))
        source_note += "# Input terminals continue from ../hk4-hub-power.yaml.\n"
        (feed_path,) = [path for path in upstream["connections"] if fanout in path[-1]]
        feed_cable, conductors = next(iter(feed_path[-2].items()))
        input_pins = feed_path[-1][fanout]
        wire_labels = upstream["cables"][feed_cable]["wirelabels"]
        input_labels = [wire_labels[core - 1] for core in conductors]
        block = sheet["connectors"][fanout]
        block["pins"] = input_pins + block["pins"]
        block["pinlabels"] = input_labels + block["pinlabels"]
        block["notes"] = (
            "HK4 feed pair shown on hk4-hub-power.svg\n"
            f'{power["branch_fuse_a"]:g} A proposed per positive branch'
        )
        sheet["tweak"]["override"][fanout] = {
            "URL": '"hk4-hub-power.svg"', "tooltip": "Open the HK4 adapter and PS1 input lead detail",
        }
        for pin, label in zip(input_pins, input_labels, strict=True):
            endpoints.append([fanout, pin, label, block["type"], feed_cable, "PROPOSED"])
        endpoints.append([feed["name"], "", feed["rating"], feed["output"], "", "SELECTED"])

    source_file = output / f"{name}.yaml"
    source_file.write_text(
        source_note + yaml.safe_dump(sheet, allow_unicode=True, sort_keys=False, default_flow_style=None, width=110),
        encoding="utf-8", newline="\n",
    )
    # Re-read the exported YAML with WireViz, exercising the same file a user can open.
    render_svg(source_file, output)
    return endpoints


def generate(output):
    with (ROOT / "cable_schedule.csv").open(encoding="utf-8", newline="") as stream:
        schedule = list(csv.DictReader(stream))
    families = yaml.safe_load((ROOT / "families.yaml").read_text(encoding="utf-8"))
    sheets = defaultdict(list)
    totals = Counter()
    wires = set()
    occupied = set()
    for row in schedule:
        name, wire, family = row["sheet"], row["cable"], row["family"]
        left, right = row["from_endpoint"], row["to_endpoint"]
        if wire in wires or right in occupied or (name != "power" and left in occupied):
            raise ValueError(f"Duplicate cable or endpoint in {wire}")
        if name != "power" and left not in [f"{name} {port}" for port in families[family]["hub_ports"]]:
            raise ValueError(f"{left} does not accept {family}")
        wires.add(wire)
        occupied.update((left, right))
        sheets[name].append(row)
        totals[family] += float(row["length_ft"])

    endpoints = []
    bom = []
    for name, cables in sheets.items():
        endpoints.extend(build_sheet(name, cables, families, output))
    for kind, family in families.items():
        members = [row for row in schedule if row["family"] == kind]
        refs = " ".join(row["cable"] for row in members)
        bom.append([family["stock"], f"{totals[kind]:g}", "ft", family["allowance_ft"], refs, "Length allowance"])
        for side in ["source", "destination"]:
            interface = family[side]
            field = "from_endpoint" if side == "source" else "to_endpoint"
            names = list(dict.fromkeys(row[field] for row in members))
            if side == "source" and "hub_ports" in family:
                for hub in (sheet for sheet in sheets if sheet != "power"):
                    for port in family["hub_ports"]:
                        end = f"{hub} {port}"
                        if end not in occupied:
                            names.append(end)
                            for pin, label in zip(interface["pins"], interface["pinlabels"], strict=True):
                                endpoints.append([end, pin, label, interface["type"], "", "PROPOSED"])
            bom.append([interface["type"], len(names), "interface", "", " / ".join(names), "Mating hardware TBD"])
    branches = sheets["power"]
    power = families["CBL-P"]
    feed = power["supply"]
    bom.append([feed["name"] + " hardwire kit", 1, "each", "", branches[0]["from_endpoint"],
                f'Owned · {feed["output"]} · {feed["rating"]}'])
    bom.append(["PS1 branch fuse", len(branches), "each", "", " ".join(row["cable"] for row in branches),
                f'{power["branch_fuse_a"]:g} A proposed. Type and final rating TBD'])
    endpoints.sort(key=lambda row: row[0])
    write_csv(output / "connector_schedule.csv", ["endpoint", "contact", "function", "interface", "cable", "status"], endpoints)
    write_csv(output / "wiring_bom.csv", ["item", "quantity", "unit", "purchase_allowance_ft", "references", "notes"], bom)
    for filename in SUPPLY_SHEETS:
        render_svg(ROOT / filename, output)


def main():
    OUTPUT.mkdir(exist_ok=True)
    build_dir = ROOT.parents[1] / "build"
    build_dir.mkdir(exist_ok=True)
    with TemporaryDirectory(prefix="wireviz-", dir=build_dir) as temporary:
        staging = Path(temporary)
        generate(staging)
        for path in staging.iterdir():
            path.replace(OUTPUT / path.name)


if __name__ == "__main__":
    main()
